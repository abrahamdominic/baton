import type { SVGProps } from "react";

/**
 * The small icon subset used by the interactive marketing islands.
 *
 * These live apart from `@/components/icons` on purpose: that module is a large
 * barrel that does not tree-shake, so importing one glyph from it dragged every
 * icon into the client bundle. Keeping the handful the simulator, state
 * explorer, calculator and mobile menu actually use here keeps the client
 * payload small.
 */
type P = SVGProps<SVGSVGElement>;

function base(props: P) {
  return {
    xmlns: "http://www.w3.org/2000/svg",
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 1.75,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    ...props,
  };
}

