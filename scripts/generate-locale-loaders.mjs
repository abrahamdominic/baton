#!/usr/bin/env node
/**
 * Generates `src/lib/i18n/loaders.generated.ts` from the `locales/` tree.
 *
 * Why codegen instead of a hand-written loader per language: `import()` needs a
 * static specifier for the bundler to code-split, so a fully dynamic
 * `import(\`@/locales/${lang}/common.json\`)` would inline every language into
 * the initial chunk. But hand-maintaining one loader block per language is
 * exactly the "temporary translation logic" lan.md §31 forbids, and it fails
 * silently when someone adds `locales/xx/` and forgets the loader.
 *
 * Codegen gets both properties: the specifiers are static, so bundling stays
 * correct, and adding a language is a directory plus a re-run of this script.
 *
 * The generated file is committed. It is a build artifact in the same sense as
 * `prisma/schema.sqlite.prisma`: deterministic, reviewable, and regenerated by
 * `npm run i18n:generate` - never hand-edited.
 *
 * Also enforces the invariant the registry depends on: every language present
 * on disk must be registered in `src/lib/i18n/registry.ts`. An unregistered
 * directory is a build-breaking error, not a silently unshipped language.
 */

import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const LOCALES_DIR = "locales";
const OUT = "src/lib/i18n/loaders.generated.ts";
const REGISTRY = "src/lib/i18n/registry.ts";

if (!existsSync(LOCALES_DIR)) {
  console.error(`No ${LOCALES_DIR}/ directory. Run from the repository root.`);
  process.exit(1);
}

/** English's namespaces define the contract; every language must match. */
const reference = readdirSync(join(LOCALES_DIR, "en"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

if (reference.length === 0) {
  console.error("locales/en/ has no namespace files.");
  process.exit(1);
}

const langs = readdirSync(LOCALES_DIR)
  .filter((d) => statSync(join(LOCALES_DIR, d)).isDirectory())
  .filter((d) => existsSync(join(LOCALES_DIR, d, "common.json")))
  .sort();

if (langs.length === 0) {
  console.error("No language directories found.");
  process.exit(1);
}

// --- Registry cross-check -------------------------------------------------
const registrySource = readFileSync(REGISTRY, "utf8");
const registered = new Set();
for (const m of registrySource.matchAll(/\bL\(\s*"([^"]+)"\s*,\s*"([^"]+)"/g)) {
  registered.add(m[1]);
  registered.add(m[2]);
}

const problems = [];
for (const lang of langs) {
  if (lang === "en") continue;
  if (!registered.has(lang)) {
    problems.push(
      `locales/${lang}/ exists but no registry entry uses language "${lang}".\n` +
        `    Add it to LOCALES in ${REGISTRY} (or set available: false and remove the directory).`,
    );
  }
  const files = readdirSync(join(LOCALES_DIR, lang))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""))
    .sort();
  const missing = reference.filter((ns) => !files.includes(ns));
  const extra = files.filter((ns) => !reference.includes(ns));
  if (missing.length) {
    problems.push(`locales/${lang}/ is missing namespace(s): ${missing.join(", ")}`);
  }
  if (extra.length) {
    problems.push(`locales/${lang}/ has namespace(s) English does not: ${extra.join(", ")}`);
  }
}

if (problems.length) {
  console.error("Locale generation failed:\n");
  for (const p of problems) console.error(`  - ${p}\n`);
  process.exit(1);
}

// --- Emit -----------------------------------------------------------------
const banner = [
  "/**",
  " * GENERATED FILE - DO NOT EDIT.",
  " *",
  " * Regenerate with:  npm run i18n:generate",
  " * Source of truth:  the locales directory tree.",
  " *",
  " * import() requires a literal specifier for the bundler to code-split, so",
  " * each language gets a generated loader. That keeps a client in English from",
  " * downloading any other language, while adding a language stays a matter of",
  " * creating a directory and re-running the generator.",
  " */",
  "",
  'import type { TranslationTree } from "./translate";',
  "",
  "export type LocaleLoaders = Record<string, () => Promise<TranslationTree>>;",
].join("\n");

// English is imported eagerly: it is the fallback layer for every request, and
// every locale payload is resolved against it.
const enImports = reference
  .map((ns) => `import en_${ns} from "@/locales/en/${ns}.json";`)
  .join("\n");

const enEntries = reference.map((ns) => `  ${ns}: en_${ns},`).join("\n");

const loaderEntries = langs
  .filter((l) => l !== "en")
  .map((lang) => {
    const imports = reference
      .map((ns) => `      import("@/locales/${lang}/${ns}.json"),`)
      .join("\n");
    const assigns = reference
      .map((ns, i) => `      ${ns}: mods[${i}]!.default,`)
      .join("\n");
    return `  ${JSON.stringify(lang)}: () =>
    Promise.all([
${imports}
    ]).then((mods) => ({
${assigns}
    })) as Promise<TranslationTree>,`;
  })
  .join("\n");

const parts = [
  banner,
  "",
  enImports,
  "",
  "/** The guaranteed-complete locale, used as the fallback layer everywhere. */",
  "export const EN_BUNDLE: TranslationTree = {",
  enEntries,
  "};",
  "",
  "/** Namespace names, derived from the resources rather than repeated by hand.",
  " *  Generated so a new namespace never needs a hand edit here. */",
  "export const NAMESPACES: readonly string[] = " + JSON.stringify(reference) + ";",
  "",
  "/** Lazy loaders for every language that has resources. */",
  "export const LOCALE_LOADERS: LocaleLoaders = {",
  loaderEntries,
  "};",
  "",
  "/** Every language that has a locales directory. */",
  "export const RESOURCE_LANGUAGES: readonly string[] = " + JSON.stringify(langs) + ";",
  "",
].join("\n");

writeFileSync(OUT, parts, "utf8");

console.log(
  `Wrote ${OUT}: ${reference.length} namespaces x ${langs.length} languages (${langs.join(", ")}).`,
);
